namespace EnemiesWithExhibits.Source.StatusEffects.Rarities.Shining
{
    public sealed class DeliciousCookieSeDef : EnemiesWithExhibitsStatusEffectTemplate
    {
        public override StatusEffectConfig MakeConfig()
        {
            StatusEffectConfig config = GetDefaultStatusEffectConfig();

            return config;
        }
    }

    [EntityLogic(typeof(DeliciousCookieSeDef))]
    public sealed class DeliciousCookieSe : EnemiesWithExhibitsStatusEffect
    {
        public DeliciousCookieSe() : base()
        {
            Value1 = 4;
        }

        protected override void OnAdded(Unit unit)
        {
            if (unit is PlayerUnit)
                Debug.LogError(this.DebugName + " should not apply to player unit.");

            base.Battle.GameRun.SetEnemyHpAndMaxHp(unit.Hp + Value1, unit.MaxHp + Value1, (EnemyUnit)unit);
        }
    }
}
