using System.Collections.Generic;
using System.Linq;
using UnityEngine;

namespace EnemiesWithExhibits.Source.StatusEffects.Rarities.Common
{
    public sealed class BeerSeDef : EnemiesWithExhibitsStatusEffectTemplate
    {
        public override StatusEffectConfig MakeConfig()
        {
            StatusEffectConfig config = GetDefaultStatusEffectConfig();

            config.RelativeEffects = new List<string>() { "TempFirepower" };

            return config;
        }
    }

    [EntityLogic(typeof(BeerSeDef))]
    public sealed class BeerSe : EnemiesWithExhibitsStatusEffect
    {
        public BeerSe() : base()
        {
            Value1 = 3;
        }

        protected override void OnAdded(Unit unit)
        {
            if (unit is PlayerUnit)
                Debug.LogError(this.DebugName + " should not apply to player unit.");

            React(new ApplyStatusEffectAction<TempFirepower>(this.Owner, Value1, null, null, null, 0.2f));
        }
    }
}
